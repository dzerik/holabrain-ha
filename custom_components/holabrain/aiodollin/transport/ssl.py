def build_client_ssl_context(
    cert_path: str, key_path: str, *, ca_data: str = AMAZON_ROOT_CA_1
) -> ssl.SSLContext:
    """Build a mutual-TLS ``SSLContext`` for the push broker.

    ``cert_path`` / ``key_path`` are the minted client certificate and its private key on
    disk (``SSLContext`` cannot load a chain from memory). The server is validated only
    against ``ca_data`` (Amazon Root CA 1 by default).
    """
    context = ssl.create_default_context(cadata=ca_data)
    context.load_cert_chain(certfile=cert_path, keyfile=key_path)
    return context
